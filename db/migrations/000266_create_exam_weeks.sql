CREATE TABLE app.exam_period_slots (
  id uuid DEFAULT gen_random_uuid() CONSTRAINT pk_exam_period_slots PRIMARY KEY,
  school_id uuid NOT NULL,
  -- Carried so a slot's sections and assessment are pinned to the period's academic year.
  academic_year_id uuid NOT NULL,
  period_id uuid NOT NULL,
  grade_level_id uuid NOT NULL,
  subject_id uuid NOT NULL,
  exam_date date NOT NULL,
  starts_at time NOT NULL,
  ends_at time NOT NULL,
  assessment_id uuid,
  notes text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_exam_period_slots_id_school UNIQUE (id, school_id),
  CONSTRAINT uq_exam_period_slots_id_year_school UNIQUE (id, academic_year_id, school_id),
  CONSTRAINT fk_exam_period_slots_school FOREIGN KEY (school_id) REFERENCES app.schools (id)
    ON UPDATE RESTRICT ON DELETE RESTRICT,
  -- Deleting a period deletes its timetable with it.
  CONSTRAINT fk_exam_period_slots_period FOREIGN KEY (period_id, academic_year_id, school_id)
    REFERENCES app.exam_periods (id, academic_year_id, school_id)
    ON UPDATE RESTRICT ON DELETE CASCADE,
  CONSTRAINT fk_exam_period_slots_grade FOREIGN KEY (grade_level_id, school_id)
    REFERENCES app.grade_levels (id, school_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT fk_exam_period_slots_subject FOREIGN KEY (subject_id, school_id)
    REFERENCES app.subjects (id, school_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  -- The gradebook assessment this exam is; deleting the assessment clears only the link.
  CONSTRAINT fk_exam_period_slots_assessment FOREIGN KEY (assessment_id, academic_year_id, school_id)
    REFERENCES app.subject_config_assessments (id, academic_year_id, school_id)
    ON UPDATE RESTRICT ON DELETE SET NULL (assessment_id),
  CONSTRAINT ck_exam_period_slots_times CHECK (ends_at > starts_at),
  CONSTRAINT ck_exam_period_slots_notes CHECK (
    notes IS NULL OR (notes = btrim(notes) AND notes <> '' AND char_length(notes) <= 500)
  ),
  CONSTRAINT ck_exam_period_slots_timestamps CHECK (updated_at >= created_at)
);

