-- The subjects of exam slots, for anyone who may see the slots: staff, and students and parents for
-- published periods. app.subjects is role-scoped (000037): a student or parent sees a subject only
-- through a class or a released mark, so an exam in a subject the student has no class row for
-- would come back without its name. Like 000255's and 000258's helpers, this reads as its owner --
-- still under tenant isolation (FORCE, current school only) -- and reveals only a subject's code and
-- name beside a slot the caller can already read. It deliberately does not widen app.subjects'
-- policy.
CREATE FUNCTION app.exam_period_slot_subjects(target_slot_ids uuid[])
RETURNS TABLE (slot_id uuid, subject_id uuid, code text, name text)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
  SELECT slot.id, subject.id, subject.code, subject.name
  FROM app.exam_period_slots AS slot
  JOIN app.exam_periods AS period
    ON period.id = slot.period_id AND period.school_id = slot.school_id
  JOIN app.subjects AS subject
    ON subject.id = slot.subject_id AND subject.school_id = slot.school_id
  WHERE slot.school_id = current_setting('app.school_id')::uuid
    AND slot.id = ANY (target_slot_ids)
    AND (
      period.status = 'published'
      OR app.current_user_is_school_admin()
      OR app.current_user_teacher_id() IS NOT NULL
    )
$function$;

ALTER FUNCTION app.exam_period_slot_subjects(uuid[]) OWNER TO studafy_admin;
REVOKE ALL ON FUNCTION app.exam_period_slot_subjects(uuid[]) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION app.exam_period_slot_subjects(uuid[]) TO studafy_app;

