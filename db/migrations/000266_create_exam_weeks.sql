-- Exam weeks (docs/plans/academic-phase2.md, WS-M): a school's exam periods (midterms, finals...),
-- the exam timetable inside each, the rooms each exam sits in, who sits where, and who invigilates.
--
-- Not to be confused with the online exams of 000102 (app.exams, app.exam_sessions: a teacher's
-- timed test taken in the app) or the external exams of 000255 (SAT, IGCSE...). These tables are all
-- named exam_period*.
--
-- PERIODS. app.exam_periods is one exam period of an academic year ("Term 1 finals"), optionally of
-- one term, with its first and last day, a kind (midterm, final...) and the grade levels it covers
-- (app.exam_period_grade_levels). A period is `draft` while leadership builds it; students, parents
-- and teachers see it in the app only once it is `published`.
--
-- SLOTS. app.exam_period_slots is one exam on the timetable: a subject for one grade level, sat by
-- some or all of that grade's sections (app.exam_period_slot_sections), on a date from a start to an
-- end time. Dates and times are the school's wall clock (like the weekly timetable's periods): the
-- apps show them in the school's timezone (app.school_settings.timezone). A slot may name the
-- gradebook assessment it is (000160's app.subject_config_assessments, e.g. "Final exam"); deleting
-- that assessment only clears the link.
--
-- ROOMS AND SEATS. The rooms an exam sits in are the school's own rooms (000009's app.rooms), listed
-- per slot in app.exam_period_slot_rooms in filling order. A room seats app.rooms.exam_capacity
-- candidates in an exam (spaced seating), or its everyday capacity when that is not set. Several
-- slots may share a room at the same time (two grades in the hall); the API keeps their seat numbers
-- apart and the room within its capacity. app.exam_period_seats is one student's seat in one slot:
-- a room of the slot and a seat number, at most one seat per student per slot and one student per
-- seat per slot. Seating is generated by a pure function (apps/api/src/modules/exam-weeks/seating.ts)
-- and adjusted by hand.
--
-- INVIGILATORS. app.exam_period_invigilators is a teacher watching one room of one slot. Clashes (a
-- teacher in two rooms at once, a student with two exams at once, a room over capacity) are worked
-- out on read by a pure function (clashes.ts), never stored.
--
-- VISIBILITY. Periods, slots, their sections and rooms, and invigilators are the school's timetable,
-- not personal data: tenant isolation only, like rooms and the weekly timetable. A seat says where a
-- student sits, so app.exam_period_seats reads like the student (app.can_read_student). The subjects
-- of published slots are read through app.exam_period_slot_subjects, because app.subjects is
-- role-scoped (000037).
--
-- Depends on 000006 (tenant helpers), 000008 (students, teachers), 000009 (academic years, terms,
-- subjects, rooms), 000147 (grade levels, sections) and 000160 (assessments, app.can_read_student).

