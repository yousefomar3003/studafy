-- ---------------------------------------------------------------------------------------------------
-- 2. Periods and the grade levels they cover
-- ---------------------------------------------------------------------------------------------------

CREATE TABLE app.exam_periods (
  id uuid DEFAULT gen_random_uuid() CONSTRAINT pk_exam_periods PRIMARY KEY,
  school_id uuid NOT NULL,
  academic_year_id uuid NOT NULL,
  term_id uuid,
  name text NOT NULL,
  kind text NOT NULL DEFAULT 'final',
  starts_on date NOT NULL,
  ends_on date NOT NULL,
  status text NOT NULL DEFAULT 'draft',
  published_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_exam_periods_id_school UNIQUE (id, school_id),
  CONSTRAINT uq_exam_periods_id_year_school UNIQUE (id, academic_year_id, school_id),
  CONSTRAINT fk_exam_periods_school FOREIGN KEY (school_id) REFERENCES app.schools (id)
    ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT fk_exam_periods_year FOREIGN KEY (academic_year_id, school_id)
    REFERENCES app.academic_years (id, school_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT fk_exam_periods_term FOREIGN KEY (term_id, academic_year_id, school_id)
    REFERENCES app.terms (id, academic_year_id, school_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT ck_exam_periods_name CHECK (
    name = btrim(name) AND name <> '' AND char_length(name) <= 120
  ),
  CONSTRAINT ck_exam_periods_kind CHECK (
    kind IN ('midterm', 'final', 'monthly', 'mock', 'other')
  ),
  CONSTRAINT ck_exam_periods_dates CHECK (ends_on >= starts_on AND ends_on - starts_on <= 90),
  CONSTRAINT ck_exam_periods_status CHECK (status IN ('draft', 'published')),
  CONSTRAINT ck_exam_periods_published_at CHECK ((status = 'published') = (published_at IS NOT NULL)),
  CONSTRAINT ck_exam_periods_timestamps CHECK (updated_at >= created_at)
);

